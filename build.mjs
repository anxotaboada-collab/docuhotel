// Docuhotel build: concatenate the source .jsx files (in the same order the
// old index.html loaded them as <script type="text/babel">), transpile JSX and
// minify into a single docuhotel.bundle.js. This removes the in-browser Babel
// transpile step, which was the main reason the app felt slow to load.
//
// The build also writes a content hash into index.html as
// `docuhotel.bundle.js?v=<hash>` so a deploy that changes the bundle
// immediately invalidates the browser cache (no-cache headers alone are not
// enough — some intermediaries and browsers ignore them).
//
//   npm run build          one-off build
//   npm run dev            rebuild on change

import { transform } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, watch, mkdirSync, copyFileSync, cpSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";

// Order matters: each file relies on globals defined by earlier ones, and
// app.jsx (last) calls ReactDOM.createRoot(...).render(...).
const FILES = [
  "tweaks-panel.jsx",
  "i18n.jsx",
  "compress.jsx",
  "api.jsx",
  "store.jsx",
  "ui.jsx",
  "auth.jsx",
  "documents.jsx",
  "viewer.jsx",
  "log.jsx",
  "admin.jsx",
  "public.jsx",
  "projects.jsx",
  "audit.jsx",
  "requests.jsx",
  "regional.jsx",
  "app.jsx",
];

const OUT = "docuhotel.bundle.js";
const HTML = "index.html";
const BUNDLE_HREF_RE = /docuhotel\.bundle\.js(?:\?v=[a-f0-9]+)?/g;

// Vercel serves only the contents of DIST. Everything else in the repo
// (source .jsx, supabase/*.sql, *.md, build.mjs, package.json) stays out
// of the public URL so attackers can't enumerate the backend by curling
// /api.jsx or /supabase/schema.sql. dist/ is rebuilt from scratch on
// every build, so anything we forget to copy here is simply not shipped.
const DIST = "dist";
const STATIC_FILES = ["styles.css", "config.js"];
const STATIC_DIRS = ["vendor"];

async function buildOnce() {
  // `;` between files so an expression at the end of one file can't merge with
  // the start of the next (api.jsx etc. start with `(function () { ... })()`).
  const source = FILES.map((f) => `\n;/* ===== ${f} ===== */\n` + readFileSync(f, "utf8")).join("\n");
  const { code, warnings } = await transform(source, {
    loader: "jsx",
    jsx: "transform", // classic runtime -> React.createElement / React.Fragment (React is a global UMD)
    target: "es2019",
    minify: true,
    legalComments: "none",
    sourcefile: "docuhotel.app.jsx",
  });
  for (const w of warnings) console.warn("esbuild:", w.text);
  const bundle = "/* Generated by build.mjs — edit the .jsx source files, not this. */\n" + code;
  writeFileSync(OUT, bundle);
  const hash = createHash("sha256").update(bundle).digest("hex").slice(0, 10);

  const html = readFileSync(HTML, "utf8");
  const next = html.replace(BUNDLE_HREF_RE, `docuhotel.bundle.js?v=${hash}`);
  if (next !== html) writeFileSync(HTML, next);

  // Stage the minimal set of files Vercel will serve. Rebuild dist/ from
  // scratch so removing a file from STATIC_FILES/STATIC_DIRS actually drops
  // it from production on the next deploy.
  if (existsSync(DIST)) rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });
  writeFileSync(join(DIST, OUT), bundle);
  writeFileSync(join(DIST, HTML), next);
  for (const f of STATIC_FILES) copyFileSync(f, join(DIST, f));
  for (const d of STATIC_DIRS) cpSync(d, join(DIST, d), { recursive: true });

  console.log(`Built ${OUT} — ${(code.length / 1024).toFixed(1)} KB — v=${hash} (also staged in ${DIST}/)`);
}

await buildOnce();

if (process.argv.includes("--watch")) {
  console.log("Watching .jsx files…");
  let timer = null;
  for (const f of FILES) {
    watch(f, () => {
      clearTimeout(timer);
      timer = setTimeout(() => buildOnce().catch((e) => console.error(e)), 120);
    });
  }
}
