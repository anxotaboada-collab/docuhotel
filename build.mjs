// Docuhotel build: concatenate the source .jsx files (in the same order the
// old index.html loaded them as <script type="text/babel">), transpile JSX and
// minify into a single docuhotel.bundle.js. This removes the in-browser Babel
// transpile step, which was the main reason the app felt slow to load.
//
//   npm run build          one-off build
//   npm run dev            rebuild on change

import { transform } from "esbuild";
import { readFileSync, writeFileSync, watch } from "node:fs";

// Order matters: each file relies on globals defined by earlier ones, and
// app.jsx (last) calls ReactDOM.createRoot(...).render(...).
const FILES = [
  "tweaks-panel.jsx",
  "i18n.jsx",
  "api.jsx",
  "store.jsx",
  "ui.jsx",
  "auth.jsx",
  "documents.jsx",
  "viewer.jsx",
  "log.jsx",
  "admin.jsx",
  "public.jsx",
  "projects.jsx",
  "audit.jsx",
  "requests.jsx",
  "regional.jsx",
  "app.jsx",
];

const OUT = "docuhotel.bundle.js";

async function buildOnce() {
  // `;` between files so an expression at the end of one file can't merge with
  // the start of the next (api.jsx etc. start with `(function () { ... })()`).
  const source = FILES.map((f) => `\n;/* ===== ${f} ===== */\n` + readFileSync(f, "utf8")).join("\n");
  const { code, warnings } = await transform(source, {
    loader: "jsx",
    jsx: "transform", // classic runtime -> React.createElement / React.Fragment (React is a global UMD)
    target: "es2019",
    minify: true,
    legalComments: "none",
    sourcefile: "docuhotel.app.jsx",
  });
  for (const w of warnings) console.warn("esbuild:", w.text);
  writeFileSync(OUT, "/* Generated by build.mjs — edit the .jsx source files, not this. */\n" + code);
  console.log(`Built ${OUT} — ${(code.length / 1024).toFixed(1)} KB`);
}

await buildOnce();

if (process.argv.includes("--watch")) {
  console.log("Watching .jsx files…");
  let timer = null;
  for (const f of FILES) {
    watch(f, () => {
      clearTimeout(timer);
      timer = setTimeout(() => buildOnce().catch((e) => console.error(e)), 120);
    });
  }
}
